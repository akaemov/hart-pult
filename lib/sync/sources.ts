/// после этого окно помечается устаревшим, а не молча показывает старое.

export type SourceId = "amocrm" | "inventory" | "metrika" | "direct" | "vk_ads" | "wordstat";

export type Source = {
  id: SourceId;
  label: string;
  /// Что пульт из него берёт — в словах пользователя, не API.
  feeds: string;
  maxAgeMinutes: number;
  /// Что должно случиться, чтобы источник заработал. Пустой список —
  /// источник уже подключён.
  needs: string[];
  /// Какие окна пульта он наполняет.
  shows: string[];
  /// Когда по плану работ.
  phase: string;
};

const HOUR = 60;

export function sourceById(id: string): Source | undefined {
  return SOURCES.find((source) => source.id === id);
}

